_lhcc_safe_dynamic_name() {
    _lhpp_safe_name "$1"
}

_lhcc_names_for_root() {
    _lhcc_real="$1"
    {
        _lhcc_static_names
        [ -d "$_lhcc_real" ] || exit 0
        for _lhcc_path in "$_lhcc_real"/*; do
            [ -f "$_lhcc_path" ] || continue
            _lhcc_name=${_lhcc_path##*/}
            _lhcc_safe_dynamic_name "$_lhcc_name" || continue
            printf '%s\n' "$_lhcc_name"
        done
    } | awk 'NF && !seen[$0]++'
}

_lhcc_link_or_copy() {
    _lhcc_source="$1"
    _lhcc_dest="$2"
    [ "$_lhcc_source" = "$_lhcc_dest" ] && return 0
    rm -f "$_lhcc_dest" 2>/dev/null || true
    ln "$_lhcc_source" "$_lhcc_dest" 2>/dev/null || \
        cp -f "$_lhcc_source" "$_lhcc_dest" 2>/dev/null || return 1
    chmod 0644 "$_lhcc_dest" 2>/dev/null || true
    return 0
}

# Drop aliases the current policy keeps stock: names retired from the policy
# (MiSansL3, clock/tabular Mono faces) and optional groups switched off. Removing
# only LuoShu's overlay copy exposes the untouched ROM file at the next mount.
_lhcc_prune_policy_aliases() {
    _lhcc_po="$1"
    _lhcc_pr="$2"
    [ -d "$_lhcc_po" ] || return 0
    for _lhcc_pn in $(_lhpp_retired_names); do
        [ -e "$_lhcc_po/$_lhcc_pn" ] || continue
        [ -e "$_lhcc_pr/$_lhcc_pn" ] || continue
        rm -f "$_lhcc_po/$_lhcc_pn" 2>/dev/null || true
    done
    for _lhcc_pp in "$_lhcc_po"/*.ttf "$_lhcc_po"/*.otf; do
        [ -f "$_lhcc_pp" ] || continue
        _lhcc_pn=${_lhcc_pp##*/}
        # Only a ROM namesake can be an alias; LuoShu-generated names stay.
        [ -e "$_lhcc_pr/$_lhcc_pn" ] || continue
        case "$_lhcc_pn" in
            # Code monospace (DroidSansMono/RobotoMono/NotoSansMono) is a policy target.
            *[Mm][Oo][Nn][Oo]*|MiSansL3*)
                _lhpp_safe_name "$_lhcc_pn" || rm -f "$_lhcc_pp" 2>/dev/null || true
                continue
                ;;
        esac
        _lhpp_group_member "$_lhcc_pn" || continue
        _lhpp_safe_name "$_lhcc_pn" && continue
        rm -f "$_lhcc_pp" 2>/dev/null || true
    done
    return 0
}

luoshu_hyperos_clock_payload_ensure() {
    _lhcc_is_hyperos || return 0
    _lhcc_payload="$(_lhcc_payload_root)"
    [ -d "$_lhcc_payload/system/fonts" ] || return 0
    _lhcc_count=0
    _lhcc_parts=0

    # Mirror only names that exist on this exact ROM. The source always comes from
    # the already-built v14.4 payload, so this is fast and cannot re-enter the v4
    # template/slot builder/validation path that previously stalled at 94%.
    for _lhcc_part in system system_ext product mi_ext vendor odm oem my_product hw_product cust; do
        _lhcc_real="$(_lhcc_root_for_part "$_lhcc_part")" || continue
        [ -d "$_lhcc_real" ] || continue
        _lhcc_overlay="$_lhcc_payload/$_lhcc_part/fonts"
        _lhcc_part_count=0
        _lhcc_prune_policy_aliases "$_lhcc_overlay" "$_lhcc_real"
        while IFS= read -r _lhcc_name; do
            [ -n "$_lhcc_name" ] || continue
            # The framework switches this exact ROM link between locale/theme
            # fonts after init. Covering it with a regular TTF freezes that route.
            # Read only the stock symlink text; never alter its /data target.
            if [ "$_lhcc_part/$_lhcc_name" = system/MiSansVF_Overlay.ttf ] && \
               [ -L "$_lhcc_real/$_lhcc_name" ] && \
               [ "$(readlink "$_lhcc_real/$_lhcc_name" 2>/dev/null)" = /data/system/fonts/theme_webview/Roboto-Regular.ttf ]; then
                rm -f "$_lhcc_overlay/$_lhcc_name" 2>/dev/null || return 1
                continue
            fi
            [ -e "$_lhcc_real/$_lhcc_name" ] || continue
            # This is a missing-slot repair, not a rebuild. Staged OEM slots may
            # have a different stock contract from their system namesake.
            [ -s "$_lhcc_overlay/$_lhcc_name" ] && continue
            _lhcc_source="$(_lhcc_source_for_name "$_lhcc_name")" || continue
            mkdir -p "$_lhcc_overlay" 2>/dev/null || continue
            if _lhcc_link_or_copy "$_lhcc_source" "$_lhcc_overlay/$_lhcc_name"; then
                _lhcc_count=$((_lhcc_count + 1))
                _lhcc_part_count=$((_lhcc_part_count + 1))
            fi
        done <<EOF_LHCC_NAMES
$(_lhcc_names_for_root "$_lhcc_real")
EOF_LHCC_NAMES
        [ "$_lhcc_part_count" -gt 0 ] 2>/dev/null && _lhcc_parts=$((_lhcc_parts + 1))
    done

    _lhcc_module="$(_lhcc_module_dir)"
    if [ "$_lhcc_count" -gt 0 ]; then
        mkdir -p "$_lhcc_module/logs" 2>/dev/null || true
        printf '[%s] HyperOS legacy physical UI slots restored: %s targets / %s partitions\n' \
            "$(date '+%Y-%m-%d %H:%M:%S' 2>/dev/null)" "$_lhcc_count" "$_lhcc_parts" \
            >> "$_lhcc_module/logs/fontswitch.log" 2>/dev/null || true
    fi
    return 0
}

