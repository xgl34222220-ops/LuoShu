# This file is sourced by post-fs-data/post-mount, so $0 belongs to the outer
# script and cannot be used as this file's directory. Resolve the compatibility
# backend from the module root first, then keep source-tree fallbacks for tests.
_hfc_base=''
for _hfc_candidate in \
    "${LUOSHU_REAL_MODDIR:-}/common/legacy_v14_4/hyperos_clock_compat.sh" \
    "${MODDIR:-}/common/legacy_v14_4/hyperos_clock_compat.sh" \
    "${MODULE_DIR:-}/common/legacy_v14_4/hyperos_clock_compat.sh" \
    "${PWD:-.}/common/legacy_v14_4/hyperos_clock_compat.sh" \
    "${0%/*}/common/legacy_v14_4/hyperos_clock_compat.sh" \
    "${0%/*}/legacy_v14_4/hyperos_clock_compat.sh"; do
    [ "$_hfc_candidate" != "/common/legacy_v14_4/hyperos_clock_compat.sh" ] || continue
    if [ -f "$_hfc_candidate" ]; then
        _hfc_base="$_hfc_candidate"
        break
    fi
done
[ -n "$_hfc_base" ] && . "$_hfc_base"
unset _hfc_candidate _hfc_base

# Replace only upright, single-font TTF/OTF UI/clock/typeface aliases. TTC files can
# carry multiple faces/index contracts; replacing those with one arbitrary font file
# is unsafe, so they remain on the ROM unless a future per-device builder proves the
# face layout explicitly. Language-specific, emoji, symbol, icon, serif, italic,
# and MiSansL3 rare-character resources also stay untouched (monospace and clock
# faces are replaced). The policy
# itself is generated from common/hyperos_physical_policy.py (single source).
# >>> BEGIN GENERATED by common/hyperos_physical_policy.py --write (do not edit)
# policy revision 4; source sha256 84de01eeb0b57063
_lhpp_groups_conf() {
    if [ -n "${LUOSHU_HYPEROS_SLOT_GROUPS_CONF:-}" ]; then
        printf '%s\n' "$LUOSHU_HYPEROS_SLOT_GROUPS_CONF"
    else
        printf '%s/config/hyperos_slot_groups.conf\n' \
            "${LUOSHU_REAL_MODDIR:-${MODDIR:-${MODULE_DIR:-/data/adb/modules/LuoShu}}}"
    fi
}

_lhpp_load_groups() {
    [ "${_LHPP_LOADED:-}" = 1 ] && return 0
    _LHPP_G_miui_ex=1; _LHPP_G_misans_ext=1; _LHPP_G_lockscreen_styles=0
    _lhpp_conf=$(_lhpp_groups_conf)
    _lhpp_cr=$(printf '\r')
    if [ -f "$_lhpp_conf" ]; then
        while IFS='=' read -r _lhpp_k _lhpp_v || [ -n "$_lhpp_k" ]; do
            case "$_lhpp_v" in *"$_lhpp_cr") _lhpp_v=${_lhpp_v%"$_lhpp_cr"} ;; esac
            case "$_lhpp_v" in 0|1) ;; *) continue ;; esac
            case "$_lhpp_k" in
                miui_ex) _LHPP_G_miui_ex=$_lhpp_v ;;
                misans_ext) _LHPP_G_misans_ext=$_lhpp_v ;;
                lockscreen_styles) _LHPP_G_lockscreen_styles=$_lhpp_v ;;
            esac
        done < "$_lhpp_conf"
    fi
    _LHPP_LOADED=1
}

# Call after editing the groups file in the same shell.
_lhpp_reload_groups() {
    _LHPP_LOADED=
    _lhpp_load_groups
}

_lhpp_group_names() {
    printf '%s\n' 'miui_ex misans_ext lockscreen_styles'
}

_lhpp_group_enabled() {
    _lhpp_load_groups
    eval "_lhpp_ge=\${_LHPP_G_$1:-0}"
    [ "$_lhpp_ge" = 1 ]
}

# Same decision as hyperos_physical_policy.safe_physical_font_name(name).
_lhpp_safe_name() {
    _lhpp_name="$1"
    case "$_lhpp_name" in */*|'') return 1 ;; esac
    case "$_lhpp_name" in *.ttf|*.otf) ;; *) return 1 ;; esac
    _lhpp_lower=$(printf '%s' "$_lhpp_name" | tr '[:upper:]' '[:lower:]')
    # SemiCondensed / DelaGothicOne are not Icon fonts; strip only those tokens.
    _lhpp_icon=$_lhpp_lower
    for _lhpp_fp in semicondensed gothicone; do
        while :; do
            case "$_lhpp_icon" in
                *"$_lhpp_fp"*) _lhpp_icon=${_lhpp_icon%%"$_lhpp_fp"*}${_lhpp_icon#*"$_lhpp_fp"} ;;
                *) break ;;
            esac
        done
    done
    case "$_lhpp_icon" in *icon*) return 1 ;; esac
    case "$_lhpp_lower" in
        *italic*|\
        *oblique*|\
        *emoji*|\
        *symbol*|\
        *serif*|\
        *arabic*|\
        *hebrew*|\
        *thai*|\
        *devanagari*|\
        *bengali*|\
        *tamil*|\
        *telugu*|\
        *malayalam*|\
        *gujarati*|\
        *gurmukhi*|\
        *kannada*|\
        *khmer*|\
        *lao*|\
        *tibetan*|\
        *myanmar*|\
        *vietnam*|\
        *japanese*|\
        *korean*|\
        *hangul*|\
        *hiragana*|\
        *katakana*|\
        *odia*|\
        *oriya*|\
        *cjkjp*|\
        *cjkkr*) return 1 ;;
    esac
    case "$_lhpp_name" in
        MiSansJP*|\
        MiSansJp*|\
        MiSansKR*|\
        MiSansKr*|\
        *CJKJP*|\
        *CJKKR*) return 1 ;;
        MiSansL3*) return 1 ;;
    esac
    # Clock faces are always targets (is_clock_face), ahead of the groups.
    case "$_lhpp_lower" in *clock*) return 0 ;; esac
    case "$_lhpp_name" in
        MitypeMono*|\
        InterMono*|\
        BebasNeue-Mono*) return 0 ;;
    esac
    case "$_lhpp_name" in
        MiSansClock*) ;;
        *)
            case "$_lhpp_name" in
        MiuiEx*|\
        Miui-*)
            _lhpp_group_enabled miui_ex
            return $?
            ;;
        MiSansRounded*|\
        MiSansC*|\
        MiLanVF*)
            _lhpp_group_enabled misans_ext
            return $?
            ;;
        Interscaled*|\
        InterMono*|\
        C800*|\
        Qinghe*|\
        ChamberiDisplay*|\
        DelaGothicOne*|\
        BebasNeue*|\
        NeumaticCompressed*|\
        GulfsDisplay*)
            _lhpp_group_enabled lockscreen_styles
            return $?
            ;;
            esac
            ;;
    esac
    case "$_lhpp_name" in
        MiSans*|\
        XiaomiSans*|\
        MiLanPro*|\
        Mitype*|\
        MiClock*|\
        AndroidClock*|\
        Roboto*|\
        GoogleSans*|\
        SourceSansPro*|\
        NotoSans-*|\
        NotoSansUI-*|\
        NotoSansSC*|\
        NotoSansTC*|\
        NotoSansHK*|\
        NotoSansHans*|\
        NotoSansHant*|\
        NotoSansCJKSC*|\
        NotoSansCJKTC*|\
        NotoSansCJKHK*|\
        NotoSansCJKsc*|\
        NotoSansCJKtc*|\
        NotoSansCJKhk*|\
        NotoSans.ttf|\
        NotoSans.otf|\
        NotoSansUI.ttf|\
        NotoSansUI.otf|\
        DroidSans.ttf|\
        DroidSans-Regular.ttf|\
        DroidSans-Bold.ttf|\
        Clockopia.ttf|\
        DroidSansMono.ttf|\
        DroidSansFallback.ttf|\
        100.ttf|\
        200.ttf|\
        300.ttf|\
        350.ttf|\
        400.ttf|\
        500.ttf|\
        600.ttf|\
        700.ttf|\
        800.ttf|\
        900.ttf) return 0 ;;
    esac
    _lhpp_stem=${_lhpp_name%.*}
    for _lhpp_family in NotoSansMono NotoSansDisplay NotoSansCondensed NotoSansSemiCondensed NotoSansExtraCondensed NotoSansVF NotoSansVariable NotoSansUIVF NotoSansMonoVF NotoSansDisplayVF NotoSansCondensedVF; do
        case "$_lhpp_stem" in
            "$_lhpp_family"|"$_lhpp_family"-*) return 0 ;;
        esac
    done
    return 1
}

