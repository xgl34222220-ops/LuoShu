}

# stdin: names (space or newline separated); stdout: accepted names, de-duplicated.
_lhpp_filter_names() {
    tr ' ' '\n' | while IFS= read -r _lhpp_fn; do
        [ -n "$_lhpp_fn" ] || continue
        _lhpp_safe_name "$_lhpp_fn" && printf '%s\n' "$_lhpp_fn"
    done | awk 'NF && !seen[$0]++'
}

