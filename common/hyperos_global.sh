        C800*|\
        Qinghe*|\
        ChamberiDisplay*|\
        DelaGothicOne*|\
        BebasNeue*|\
        NeumaticCompressed*|\
        GulfsDisplay*)
            _lhpp_group_enabled lockscreen_styles
            return $?
            ;;
            esac
            ;;
    esac
    case "$_lhpp_name" in
        MiSans*|\
        XiaomiSans*|\
        MiLanPro*|\
        Mitype*|\
        MiClock*|\
        AndroidClock*|\
        Roboto*|\
        GoogleSans*|\
        SourceSansPro*|\
        NotoSans-*|\
        NotoSansUI-*|\
        NotoSansSC*|\
        NotoSansTC*|\
        NotoSansHK*|\
        NotoSansHans*|\
        NotoSansHant*|\
        NotoSansCJKSC*|\
        NotoSansCJKTC*|\
        NotoSansCJKHK*|\
        NotoSansCJKsc*|\
        NotoSansCJKtc*|\
        NotoSansCJKhk*|\
        NotoSans.ttf|\
        NotoSans.otf|\
        NotoSansUI.ttf|\
        NotoSansUI.otf|\
        DroidSans.ttf|\
        DroidSans-Regular.ttf|\
        DroidSans-Bold.ttf|\
        Clockopia.ttf|\
        DroidSansMono.ttf|\
        DroidSansFallback.ttf|\
        100.ttf|\
        200.ttf|\
        300.ttf|\
        350.ttf|\
        400.ttf|\
        500.ttf|\
        600.ttf|\
        700.ttf|\
        800.ttf|\
        900.ttf) return 0 ;;
    esac
    _lhpp_stem=${_lhpp_name%.*}
    for _lhpp_family in NotoSansMono NotoSansDisplay NotoSansCondensed NotoSansSemiCondensed NotoSansExtraCondensed NotoSansVF NotoSansVariable NotoSansUIVF NotoSansMonoVF NotoSansDisplayVF NotoSansCondensedVF; do
        case "$_lhpp_stem" in
            "$_lhpp_family"|"$_lhpp_family"-*) return 0 ;;
        esac
    done
