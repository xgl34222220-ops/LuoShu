        *cjkkr*) return 1 ;;
    esac
    case "$_lhpp_name" in
        MiSansJP*|\
        MiSansJp*|\
        MiSansKR*|\
        MiSansKr*|\
        *CJKJP*|\
        *CJKKR*) return 1 ;;
        MiSansL3*) return 1 ;;
    esac
    case "$_lhpp_lower" in *mono*) return 1 ;; esac
    case "$_lhpp_name" in
        MiSansClock*) ;;
        *)
            case "$_lhpp_name" in
        MiuiEx*|\
        Miui-*)
            _lhpp_group_enabled miui_ex
            return $?
            ;;
        MiSansRounded*|\
        MiSansC*|\
