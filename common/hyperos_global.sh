# Optional HyperOS slot groups (MiuiEx/Miui, MiSans Rounded/C/MiLanVF, lock
# screen styles) that exist on this ROM and are enabled in
# config/hyperos_slot_groups.conf.
_hyperos_group_ui_files() {
    while IFS='|' read -r _real _overlay; do
        [ -d "$_real" ] || continue
        for _path in "$_real"/*.ttf "$_real"/*.otf; do
            [ -f "$_path" ] || continue
