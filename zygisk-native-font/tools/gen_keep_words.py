#!/usr/bin/env python3
"""Generate src/keep_words.inc: the name tokens that make the native verdict keep a font.

Sources of truth (kept in sync by tests/keep_words_sync_test.py):
  * common/font_import.sh   import_is_icon_name / import_is_color_font_name case patterns
  * common/font_inventory.py GENERIC_DENY_FILE_TOKENS (minus tokens the cmap stage handles)
  * EXTRA_TOKENS below: well-known icon / math / digit font families.

Usage: gen_keep_words.py [--check]   (--check exits 1 when the checked-in file is stale)
"""
from __future__ import annotations

import ast
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
MODULE = HERE.parent
REPO = MODULE.parent
OUT = MODULE / "src" / "keep_words.inc"

# Tokens from GENERIC_DENY_FILE_TOKENS that are NOT a reason to keep an app font natively:
#   style words (serif/mono) and script names are body text faces; monospace is decided by the
#   post/OS-2 metrics stage and script coverage by the cmap stage.
INVENTORY_IGNORED = {
    "serif", "mono", "monospace",
    "adlam", "arabic", "hebrew", "thai", "devanagari", "bengali", "tamil",
    "telugu", "malayalam", "gujarati", "gurmukhi", "kannada", "khmer", "lao",
    "tibetan", "myanmar", "sinhala", "ethiopic", "georgian", "armenian",
    "japanese", "korean", "hangul", "hiragana", "katakana", "odia", "oriya",
    "cjkjp", "cjkkr",
}

EXTRA_TOKENS = (
    "iconfont", "fontawesome", "fa-", "materialicons", "materialsymbols", "remixicon",
    "codicon", "ionicons", "feather", "katex", "mathjax", "stix", "emoji", "digit",
    "number", "lcd", "segment",
)


def shell_case_tokens(func: str) -> list[str]:
    text = (REPO / "common" / "font_import.sh").read_text(encoding="utf-8")
    m = re.search(rf"^{re.escape(func)}\(\)\s*\{{(.*?)^\}}", text, re.S | re.M)
    if not m:
        raise SystemExit(f"{func} not found in common/font_import.sh")
    case = re.search(r"case\s+\"\$_lower\"\s+in\s+(.*?)\)", m.group(1), re.S)
    if not case:
        raise SystemExit(f"case pattern not found in {func}")
    out = []
    for pat in case.group(1).split("|"):
        pat = pat.strip()
        if not (pat.startswith("*") and pat.endswith("*")) or len(pat) < 3:
            raise SystemExit(f"unsupported pattern {pat!r} in {func}")
        out.append(pat[1:-1])
    return out


def inventory_tokens() -> list[str]:
    tree = ast.parse((REPO / "common" / "font_inventory.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "GENERIC_DENY_FILE_TOKENS" for t in node.targets
        ):
            return [str(v) for v in ast.literal_eval(node.value)]
    raise SystemExit("GENERIC_DENY_FILE_TOKENS not found in common/font_inventory.py")


def build() -> str:
    tokens: list[str] = []
    for tok in (
        shell_case_tokens("import_is_icon_name")
        + shell_case_tokens("import_is_color_font_name")
        + [t for t in inventory_tokens() if t not in INVENTORY_IGNORED]
        + list(EXTRA_TOKENS)
    ):
        tok = tok.lower()
        if tok and tok not in tokens:
            tokens.append(tok)
    lines = [
        "// Generated by tools/gen_keep_words.py. Do not edit by hand.",
        "// Lower-case substrings; a font whose file/asset name or name-table family matches one is kept.",
    ]
    lines += [f'LSNF_KEEP_WORD("{t}")' for t in tokens]
    return "\n".join(lines) + "\n"


def main() -> int:
    content = build()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            sys.stderr.write("src/keep_words.inc is stale; run tools/gen_keep_words.py\n")
            return 1
        print("keep_words.inc in sync")
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
